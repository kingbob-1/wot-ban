# ------------------------------------------------------------------ 环境检查
def read_app_version(cfg: LauncherConfig) -> str:
    """从 src/config.py 读取 app_version（避免版本号写两份）。"""
    config_path = cfg.project_root / "src" / "config.py"
    try:
        text = config_path.read_text(encoding="utf-8")
    except OSError:
        return "0.0.0"
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith('app_version: str = "'):
            return stripped.split('"')[1]
    return "0.0.0"


def resolve_csc_path(cfg: LauncherConfig) -> Optional[str]:
    """定位 csc.exe：显式参数 → %WINDIR% 下的 .NET Framework → PATH。"""
    if cfg.csc_path:
        candidate = Path(cfg.csc_path).expanduser()
        return str(candidate) if candidate.is_file() else None
    windir = os.environ.get("WINDIR") or os.environ.get("SystemRoot") or ""
    if windir:
        for parts in CSC_SEARCH_DIRS:
            candidate = Path(windir).joinpath(*parts)
            if candidate.is_file():
                return str(candidate)
    return shutil.which("csc")


def probe_pillow() -> dict:
    """探测 Pillow 是否可用。"""
    try:
        from PIL import Image, ImageDraw  # noqa: F401

        return {"ok": True, "version": getattr(Image, "__version__", ""), "error": ""}
    except ImportError as exc:
        return {"ok": False, "version": "", "error": str(exc)}


def probe_runtime_layout(cfg: LauncherConfig) -> dict:
    """探测启动器可用的解释器布局（仅信息展示，不阻塞构建）。"""
    root = cfg.project_root
    local_dir = root / "runtime"
    dev_dir = root.parent / "runtime"
    found = []
    for name in ("pythonw.exe", "python.exe"):
        if (local_dir / name).is_file():
            found.append("包内 runtime/%s" % name)
        elif (dev_dir / name).is_file():
            found.append("开发布局 ../runtime/%s" % name)
        if shutil.which(name):
            found.append("PATH %s" % name)
    return {
        "local_dir": local_dir,
        "dev_dir": dev_dir,
        "found": found,
    }


def collect_problems(cfg: LauncherConfig) -> list:
    """收集环境问题，返回 [(level, 文本)]；level=error 时构建失败。"""
    problems = []
    if platform.system() != "Windows":
        problems.append(("error", "当前系统不是 Windows：exe 启动器仅面向 Windows"))
    if not (cfg.project_root / "src" / "main.py").is_file():
        problems.append(("error", "缺少产品入口：%s" % (cfg.project_root / "src" / "main.py")))
    pill = probe_pillow()
    if not pill["ok"]:
        problems.append(("error", "Pillow 不可用（生成图标必需）：%s" % pill["error"]))
    csc = resolve_csc_path(cfg)
    if not csc:
        problems.append(("error", "未找到 csc.exe：请安装 .NET Framework 4.x 或使用 --csc 指定路径"))
    layout = probe_runtime_layout(cfg)
    if not layout["found"]:
        problems.append(("warning", "未探测到 pythonw.exe/python.exe：启动器运行时会依赖 PATH，请确认部署环境"))
    if not cfg.output_exe.parent.is_dir():
        problems.append(("error", "exe 输出目录不存在：%s" % cfg.output_exe.parent))
    return problems


