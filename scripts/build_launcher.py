# ------------------------------------------------------------------ 原创图标
def unit_box(x0: float, y0: float, x1: float, y1: float, scale: float) -> list:
    """把 256 坐标系矩形换算成当前像素坐标。"""
    return [x0 * scale, y0 * scale, x1 * scale, y1 * scale]


def unit_point(x: float, y: float, scale: float) -> tuple:
    """把 256 坐标系点换算成当前像素坐标。"""
    return (x * scale, y * scale)


def unit_circle(cx: float, cy: float, radius: float, scale: float) -> list:
    """把 256 坐标系圆换算成当前像素包围盒。"""
    return [(cx - radius) * scale, (cy - radius) * scale, (cx + radius) * scale, (cy + radius) * scale]


def draw_icon_background(image) -> None:
    """绘制圆角深橄榄绿渐变底（衬出坦克剪影）。"""
    from PIL import Image, ImageDraw

    dim = image.size[0]
    scale = dim / 256.0
    gradient = Image.new("RGBA", (1, dim))
    for y in range(dim):
        ratio = y / float(max(1, dim - 1))
        color = tuple(
            int(round(ICON_BG_TOP[channel] + (ICON_BG_BOTTOM[channel] - ICON_BG_TOP[channel]) * ratio))
            for channel in range(4)
        )
        gradient.putpixel((0, y), color)
    gradient = gradient.resize((dim, dim), Image.Resampling.NEAREST)
    mask = Image.new("L", (dim, dim), 0)
    mask_draw = ImageDraw.Draw(mask)
    radius = 46.0 * scale
    mask_draw.rounded_rectangle([0, 0, dim - 1, dim - 1], radius=radius, fill=255)
    image.paste(gradient, (0, 0), mask)
    rim_draw = ImageDraw.Draw(image)
    rim_draw.rounded_rectangle(
        [0, 0, dim - 1, dim - 1],
        radius=radius,
        outline=ICON_RIM,
        width=max(ICON_SUPERSAMPLE, int(round(1.2 * scale))),
    )


def draw_tank_silhouette(size: int, image) -> None:
    """在给定画布上绘制原创坦克剪影（履带 + 车体 + 炮塔 + 炮管）。"""
    from PIL import ImageDraw

    dim = image.size[0]
    scale = dim / 256.0
    supersample = dim / float(size)
    draw = ImageDraw.Draw(image)
    tank = ICON_TANK
    # 履带（圆角长条）
    draw.rounded_rectangle(unit_box(34, 144, 222, 190, scale), radius=23 * scale, fill=tank)
    # 负重轮：小尺寸省略，保证 16/32 px 下轮廓干净
    if size >= 48:
        wheel_radius = 9
        for center_x in (57.0, 92.5, 128.0, 163.5, 199.0):
            draw.ellipse(unit_circle(center_x, 167.0, wheel_radius, scale), fill=ICON_WHEEL)
    # 车体（前装甲倾斜的梯形）
    draw.polygon(
        [
            unit_point(54, 148, scale),
            unit_point(210, 148, scale),
            unit_point(194, 102, scale),
            unit_point(70, 102, scale),
        ],
        fill=tank,
    )
    # 炮塔（上窄下宽的梯形）
    draw.polygon(
        [
            unit_point(88, 104, scale),
            unit_point(190, 104, scale),
            unit_point(176, 72, scale),
            unit_point(102, 72, scale),
        ],
        fill=tank,
    )
    # 指挥塔小凸起：仅在较大尺寸绘制，避免小图标糊成一团
    if size >= 64:
        draw.rounded_rectangle(unit_box(110, 64, 142, 76, scale), radius=6 * scale, fill=tank)
    # 炮管（小尺寸下强制最小粗细，保证可见）
    barrel_height = max(10.0 * scale, 1.6 * supersample)
    barrel_center_y = 88.0 * scale
    draw.rounded_rectangle(
        [
            166.0 * scale,
            barrel_center_y - barrel_height / 2.0,
            242.0 * scale,
            barrel_center_y + barrel_height / 2.0,
        ],
        radius=barrel_height / 2.0,
        fill=tank,
    )
    # 炮口制退器（炮管末端的加宽块）
    muzzle_height = max(16.0 * scale, 2.0 * supersample)
    draw.rounded_rectangle(
        [
            230.0 * scale,
            barrel_center_y - muzzle_height / 2.0,
            246.0 * scale,
            barrel_center_y + muzzle_height / 2.0,
        ],
        radius=min(muzzle_height / 2.0, 3.0 * scale),
        fill=tank,
    )


def render_tank_icon(size: int):
    """渲染指定尺寸的原创坦克图标（超采样后缩小，保证边缘平滑）。"""
    from PIL import Image

    dim = size * ICON_SUPERSAMPLE
    image = Image.new("RGBA", (dim, dim), (0, 0, 0, 0))
    draw_icon_background(image)
    draw_tank_silhouette(size, image)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def write_tank_icon(cfg: LauncherConfig) -> dict:
    """生成多尺寸原创坦克图标 ICO 并回读校验。"""
    from PIL import Image

    images = {size: render_tank_icon(size) for size in ICON_SIZES}
    base = images[256]
    append_images = [images[size] for size in ICON_SIZES if size != 256]
    cfg.icon_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        base.save(
            str(cfg.icon_path),
            format="ICO",
            sizes=[(size, size) for size in ICON_SIZES],
            append_images=append_images,
        )
    except OSError as exc:
        raise BuildError(
            "写出图标 ICO 失败：%s" % exc,
            "检查 assets 目录是否可写，或是否有其他程序占用了该文件",
        ) from exc
    try:
        with Image.open(str(cfg.icon_path)) as icon:
            embedded = sorted(icon.info.get("sizes", []))
    except OSError as exc:
        raise BuildError("回读图标 ICO 失败：%s" % exc, "删除 assets/app.ico 后重试") from exc
    expected = [(size, size) for size in ICON_SIZES]
    if embedded != expected:
        raise BuildError(
            "图标尺寸不完整：期望 %s，实际 %s" % (list(ICON_SIZES), [item[0] for item in embedded]),
            "删除 assets/app.ico 后重试；如仍失败请检查 Pillow 版本（>= 9）",
        )
    return {
        "sizes": [item[0] for item in embedded],
        "size_bytes": cfg.icon_path.stat().st_size,
    }


# ------------------------------------------------------------------ C# 启动器
def cs_literal(text: str) -> str:
    """把 Python 文本转成只含 ASCII 的 C# 字符串字面量（中文转 \\uXXXX）。"""
    pieces = ['"']
    for char in text:
        code = ord(char)
        if char == '"':
            pieces.append('\\"')
        elif char == "\\":
            pieces.append("\\\\")
        elif char == "\n":
            pieces.append("\\n")
        elif char == "\r":
            pieces.append("\\r")
        elif char == "\t":
            pieces.append("\\t")
        elif 32 <= code < 127:
            pieces.append(char)
        else:
            pieces.append("\\u%04X" % code)
    pieces.append('"')
    return "".join(pieces)


def format_assembly_version(version: str) -> str:
    """把产品版本号规范成 Windows 资源版本需要的四段式（如 0.2.0 -> 0.2.0.0）。"""
    parts = [part for part in version.replace("-", ".").split(".") if part.isdigit()]
    while len(parts) < 4:
        parts.append("0")
    return ".".join(parts[:4])


def build_csharp_source(cfg: LauncherConfig) -> str:
    """生成 C# 启动器源码（纯 ASCII，避免 csc 源码编码问题）。"""
    source = CSHARP_TEMPLATE
    replacements = {
        "@@TITLE@@": cs_literal(UI_TITLE),
        "@@MSG_NO_MAIN@@": cs_literal(UI_MSG_NO_MAIN),
        "@@MSG_NO_PYTHON@@": cs_literal(UI_MSG_NO_PYTHON),
        "@@MSG_LAUNCH_FAIL@@": cs_literal(UI_MSG_LAUNCH_FAIL),
        "@@HINT_FIND_PYTHON@@": cs_literal(UI_HINT_FIND_PYTHON),
        "@@HINT_PATH_ENTRY@@": cs_literal(UI_HINT_PATH_ENTRY),
        "@@ASSEMBLY_TITLE@@": cs_literal(UI_TITLE),
        "@@ASSEMBLY_PRODUCT@@": cs_literal(UI_PRODUCT),
        "@@ASSEMBLY_VERSION@@": cs_literal(format_assembly_version(read_app_version(cfg))),
    }
    for token, literal in replacements.items():
        if token not in source:
            raise BuildError("C# 模板缺少占位符：%s" % token, "检查 scripts/build_launcher.py 的 CSHARP_TEMPLATE")
        source = source.replace(token, literal)
    if not source.isascii():
        raise BuildError(
            "C# 源码包含非 ASCII 字符（csc 源码编码风险）",
            "检查 scripts/build_launcher.py 中的模板与中文文案处理",
        )
    return source


def write_csharp_source(cfg: LauncherConfig, state: BuildState) -> Path:
    """把生成的 C# 源码写入临时目录。"""
    source = build_csharp_source(cfg)
    cs_path = state.work_dir / "WotBanLauncher.cs"
    cs_path.write_text(source, encoding="ascii", newline="\r\n")
    return cs_path


def compile_launcher(cfg: LauncherConfig, state: BuildState) -> Path:
    """用 csc.exe 编译 Winexe 启动器（先出 ASCII 临时名，再部署为中文名）。"""
    csc = resolve_csc_path(cfg)
    if not csc:
        raise BuildError(
            "未找到 csc.exe，无法编译启动器",
            "安装 .NET Framework 4.x（Windows 自带），或用 --csc 指定 csc.exe 完整路径",
        )
    # 直接以中文名输出，确保 PE 资源里的 OriginalFilename 与最终产物一致
    built_exe = state.work_dir / cfg.exe_name
    command = [
        csc,
        "/nologo",
        "/target:winexe",
        "/platform:anycpu",
        "/optimize+",
        "/r:System.Windows.Forms.dll",
        "/win32icon:" + str(cfg.icon_path),
        "/out:" + str(built_exe),
        str(state.cs_path),
    ]
    try:
        result = subprocess.run(
            command,
            cwd=str(state.work_dir),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=180,
        )
    except OSError as exc:
        raise BuildError("无法启动 csc.exe：%s" % exc, "检查 .NET Framework 是否完整安装") from exc
    if result.returncode != 0 or not built_exe.is_file():
        tail = ((result.stdout or "") + (result.stderr or "")).strip()[-1200:]
        raise BuildError(
            "C# 启动器编译失败（csc 退出码 %d）" % result.returncode,
            "编译器输出：%s" % (tail or "无输出"),
        )
    return built_exe


def deploy_launcher(cfg: LauncherConfig, state: BuildState) -> Path:
    """把编译产物部署到项目根（中文文件名）。"""
    try:
        shutil.copy2(state.built_exe, cfg.output_exe)
    except OSError as exc:
        raise BuildError(
            "部署 exe 失败：%s" % exc,
            "检查目标文件是否被占用（先关闭正在运行的启动器），或更换 --out 输出路径",
        ) from exc
    return cfg.output_exe


def verify_launcher(cfg: LauncherConfig) -> dict:
    """自检：运行 exe --version，检查输出与退出码。"""
    expected_version = read_app_version(cfg)
    try:
        result = subprocess.run(
            [str(cfg.output_exe), "--version"],
            cwd=str(cfg.project_root),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=120,
        )
    except subprocess.TimeoutExpired:
        return {
            "ok": False,
            "exit_code": None,
            "stdout": "",
            "detail": "exe --version 执行超时（120 秒）",
            "expected": "v%s" % expected_version,
        }
    except OSError as exc:
        return {
            "ok": False,
            "exit_code": None,
            "stdout": "",
            "detail": "无法执行 exe：%s" % exc,
            "expected": "v%s" % expected_version,
        }
    stdout = (result.stdout or "").strip()
    stderr = (result.stderr or "").strip()
    expected_text = "v%s" % expected_version
    ok = result.returncode == 0 and expected_text in stdout
    detail = "通过" if ok else "退出码=%s，期望输出包含 %s；stderr=%s" % (
        result.returncode,
        expected_text,
        stderr[-300:] or "无",
    )
    return {
        "ok": ok,
        "exit_code": result.returncode,
        "stdout": stdout,
        "stderr": stderr,
        "expected": expected_text,
        "detail": detail,
    }


# ------------------------------------------------------------------ 构建流程
def execute_build(cfg: LauncherConfig) -> int:
    """执行完整构建；返回退出码。"""
    total = 6
    start_all = time.perf_counter()
    state = BuildState()

    step_start = time.perf_counter()
    problems = collect_problems(cfg)
    errors = [item for item in problems if item[0] == "error"]
    for level, text in problems:
        print("[%s] %s" % ("错误" if level == "error" else "警告", text))
    if errors:
        raise BuildError(
            "构建环境检查未通过（%d 个错误）" % len(errors),
            "先运行 python scripts/build_launcher.py --check 查看完整环境检查结果",
        )
    print_step(1, total, "检查构建环境", time.perf_counter() - step_start, "完成")

    step_start = time.perf_counter()
    icon_info = write_tank_icon(cfg)
    state.icon_sizes = icon_info["sizes"]
    state.icon_size_bytes = icon_info["size_bytes"]
    print(
        "      原创坦克图标：%s（%s，尺寸 %s）"
        % (cfg.icon_path.name, format_size(state.icon_size_bytes), "/".join(str(item) for item in state.icon_sizes))
    )
    print_step(2, total, "生成原创坦克图标", time.perf_counter() - step_start, "完成")

    state.work_dir = Path(tempfile.mkdtemp(prefix="wot_ban_launcher_"))
    print("      临时工作目录：%s" % state.work_dir)

    step_start = time.perf_counter()
    state.cs_path = write_csharp_source(cfg, state)
    print("      已生成 C# 源码：%s（%d 字节，纯 ASCII）" % (state.cs_path.name, state.cs_path.stat().st_size))
    print_step(3, total, "生成 C# 启动器源码", time.perf_counter() - step_start, "完成")

    step_start = time.perf_counter()
    state.built_exe = compile_launcher(cfg, state)
    state.exe_size_bytes = state.built_exe.stat().st_size
    print(
        "      编译完成：%s（%s）"
        % (state.built_exe.name, format_size(state.exe_size_bytes))
    )
    print_step(4, total, "编译薄 exe", time.perf_counter() - step_start, "完成")

    step_start = time.perf_counter()
    deploy_launcher(cfg, state)
    state.exe_size_bytes = cfg.output_exe.stat().st_size
    print("      产物：%s（%s）" % (cfg.output_exe, format_size(state.exe_size_bytes)))
    if state.exe_size_bytes > EXE_SIZE_LIMIT:
        print(
            "[警告] exe 体积 %s 超过 100 KB 预算：请检查启动器是否引入了多余依赖"
            % format_size(state.exe_size_bytes)
        )
    print_step(5, total, "部署到项目根", time.perf_counter() - step_start, "完成")

    step_start = time.perf_counter()
    if cfg.skip_verify:
        print("      已跳过自检（--skip-verify）")
    else:
        state.verify = verify_launcher(cfg)
        print("      自检命令：%s --version" % cfg.output_exe.name)
        print("      输出：%s" % (state.verify.get("stdout", "").replace("\n", " | ") or "（空）"))
        print("      退出码：%s" % state.verify.get("exit_code"))
        if not state.verify["ok"]:
            raise BuildError(
                "exe 自检未通过：%s" % state.verify["detail"],
                "exe 已生成但 --version 自检失败，请检查解释器布局（runtime 目录）与 src/main.py",
            )
    print_step(6, total, "自检 exe --version", time.perf_counter() - step_start, "完成")

    print("")
    print("[完成] 薄 exe 启动器构建成功，总耗时 %s" % format_duration(time.perf_counter() - start_all))
    print("       exe  : %s" % cfg.output_exe)
    print("       大小 : %s（预算 100 KB 以内）" % format_size(state.exe_size_bytes))
    print("       icon : %s（%s）" % (cfg.icon_path, "/".join(str(item) for item in state.icon_sizes)))
    if state.verify:
        print("       自检 : %s（退出码 %s）" % (state.verify.get("stdout", ""), state.verify.get("exit_code")))
    if cfg.keep_work:
        print("       临时目录已保留：%s" % state.work_dir)
    else:
        shutil.rmtree(state.work_dir, ignore_errors=True)
    return 0


# ------------------------------------------------------------------ 主函数
def parse_args(argv: list) -> argparse.Namespace:
    """解析命令行参数。"""
    parser = argparse.ArgumentParser(
        prog="build_launcher.py",
        description="构建 wot-ban 薄 exe 启动器（原创坦克图标 + C# Winexe 薄壳）",
    )
    parser.add_argument("--check", action="store_true", help="只检查构建环境，不写任何文件")
    parser.add_argument("--csc", default="", help="csc.exe 路径（默认自动搜索 .NET Framework 4.x）")
    parser.add_argument("--out", default="", help="exe 输出路径（默认项目根 坦克世界封号查询.exe）")
    parser.add_argument("--icon", default="", help="图标输出路径（默认 assets/app.ico）")
    parser.add_argument("--skip-verify", action="store_true", help="跳过 exe --version 自检")
    parser.add_argument("--keep-work", action="store_true", help="保留临时工作目录（排查编译问题用）")
    return parser.parse_args(argv)


def main(argv: list) -> int:
    """主入口：参数解析 -> 配置组装 -> 环境检查或执行构建。"""
    setup_console()
    args = parse_args(argv)
    base_path = "."
    project_root = Path(__file__).resolve().parent.parent
    cfg = LauncherConfig(
        project_root=project_root,
        icon_path=Path(args.icon) if args.icon else Path("assets") / APP_ICON_NAME,
        output_exe=Path(args.out) if args.out else None,
        csc_path=args.csc,
        keep_work=args.keep_work,
        skip_verify=args.skip_verify,
    )
    cfg.resolve_paths()
    print_header(cfg)
    print("基路径     : %s" % base_path)
    start_all = time.perf_counter()
    if args.check:
        problems = collect_problems(cfg)
        print_check_report(cfg, problems)
        print("总耗时 %s" % format_duration(time.perf_counter() - start_all))
        return 0 if not [item for item in problems if item[0] == "error"] else 1
    try:
        return execute_build(cfg)
    except BuildError as exc:
        print("")
        print("[失败] %s" % exc.message)
        if exc.hint:
            print("[建议] %s" % exc.hint)
        print("总耗时 %s" % format_duration(time.perf_counter() - start_all))
        return 1
    except KeyboardInterrupt:
        print("")
        print("[中止] 用户中断构建")
        print("总耗时 %s" % format_duration(time.perf_counter() - start_all))
        return 130
    except Exception as exc:  # noqa: BLE001 - 顶层兜底：未预期错误给出中文提示
        print("")
        print("[失败] 未预期错误：%s" % exc)
        print("[建议] 加 --keep-work 保留临时目录后重试；若仍失败请附完整输出反馈")
        print("总耗时 %s" % format_duration(time.perf_counter() - start_all))
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
